/**
 * Generates lib/bridge/languages.json and docs/guides/language-coverage.md from the speech provider's own
 * supported-language list — Verbo never hardcodes a list of languages.
 *
 * Source: Soniox `GET https://api.soniox.com/v1/models` (Bearer SONIOX_API_KEY) →
 *   models[].languages[].{code,name}, models[].one_way_translation, models[].translation_targets,
 *   models[].transcription_mode
 *   (docs.soniox.com/stt/api-reference/models/get_models, checked Nov 4, 2026)
 *
 * Tiers:
 *   A — native-speaker reviewed AND real audio tested (only codes listed in lib/bridge/tier-a.json)
 *   B — real-time STT + translation supported by the provider; templates auto-verified; labelled machine-translated
 *   C — text-assisted only (no real-time STT or no translation)
 *
 * Usage: npm run gen-languages
 */
import "dotenv/config";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

type Lang = { code: string; name: string };
type Model = {
  id: string;
  transcription_mode?: string;
  languages?: Lang[];
  translation_targets?: unknown;
  /** "all_languages" when every listed language can be translated (observed Nov 5, 2026). */
  one_way_translation?: unknown;
};

/** Writing direction is a property of the script, derived from CLDR via Intl where available. */
function direction(code: string): "rtl" | "ltr" {
  try {
    const loc = new Intl.Locale(code) as Intl.Locale & { getTextInfo?: () => { direction: string }; textInfo?: { direction: string } };
    const info = loc.getTextInfo?.() ?? loc.textInfo;
    if (info?.direction === "rtl") return "rtl";
  } catch {}
  return "ltr";
}

function nativeName(code: string, fallback: string): string {
  try {
    const n = new Intl.DisplayNames([code], { type: "language" }).of(code);
    return n && n !== code ? n : fallback;
  } catch {
    return fallback;
  }
}

function translationCodes(m: Model): Set<string> {
  const out = new Set<string>();
  const walk = (v: unknown) => {
    if (typeof v === "string") out.add(v);
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  walk(m.translation_targets);
  return out;
}

async function main() {
  const key = process.env.SONIOX_API_KEY;
  if (!key) {
    console.error("SONIOX_API_KEY is not set — cannot fetch the provider language list. Nothing generated.");
    process.exit(1);
  }
  const res = await fetch("https://api.soniox.com/v1/models", { headers: { Authorization: `Bearer ${key}` } });
  if (!res.ok) {
    console.error(`Soniox /v1/models failed: HTTP ${res.status}`);
    process.exit(1);
  }
  const { models } = (await res.json()) as { models: Model[] };

  const tierA: string[] = existsSync("lib/bridge/tier-a.json") ? JSON.parse(readFileSync("lib/bridge/tier-a.json", "utf8")) : [];
  const langs = new Map<string, { code: string; name: string; realtime: boolean; translation: boolean; models: string[] }>();
  for (const m of models) {
    const tr = translationCodes(m);
    const realtime = (m.transcription_mode ?? "").includes("real");
    for (const l of m.languages ?? []) {
      const cur = langs.get(l.code) ?? { code: l.code, name: l.name, realtime: false, translation: false, models: [] };
      cur.realtime ||= realtime;
      cur.translation ||= m.one_way_translation === "all_languages" || tr.has(l.code);
      if (realtime) cur.models.push(m.id);
      langs.set(l.code, cur);
    }
  }

  const list = [...langs.values()]
    .map((l) => {
      const tier = tierA.includes(l.code) ? "A" : l.realtime && l.translation ? "B" : "C";
      return {
        code: l.code,
        englishName: l.name,
        nativeName: nativeName(l.code, l.name),
        dir: direction(l.code),
        tier,
        reviewed: tier === "A",
        // first real-time model in the provider's own order (currently its newest)
        stt: { realtime: l.realtime, model: l.models[0] ?? null },
        translation: l.translation,
      };
    })
    .sort((a, b) => a.englishName.localeCompare(b.englishName));

  const counts = { A: 0, B: 0, C: 0 } as Record<string, number>;
  list.forEach((l) => counts[l.tier]++);

  mkdirSync("lib/bridge", { recursive: true });
  writeFileSync(
    "lib/bridge/languages.json",
    JSON.stringify({ generatedAt: new Date().toISOString(), source: "soniox GET /v1/models", counts, languages: list }, null, 2) + "\n",
  );

  const rows = list.map((l) => `| ${l.englishName} | ${l.nativeName} | \`${l.code}\` | ${l.dir.toUpperCase()} | ${l.tier} | ${l.reviewed ? "yes" : "no"} |`);
  writeFileSync(
    "docs/guides/language-coverage.md",
    `# Language coverage\n\n_Generated by \`scripts/gen-languages.ts\` from the speech provider's own list (Soniox \`GET /v1/models\`) on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand._\n\n` +
      `| Tier | Meaning | Count |\n|---|---|---|\n` +
      `| A | Native-speaker reviewed and tested with real audio | ${counts.A} |\n` +
      `| B | Real-time speech + translation; templates auto-verified; shown as machine-translated | ${counts.B} |\n` +
      `| C | Text-assisted only | ${counts.C} |\n\n` +
      `Verbo never claims "any language". These are the real counts.\n\n` +
      `| Language | Native name | Code | Direction | Tier | Reviewed |\n|---|---|---|---|---|---|\n${rows.join("\n")}\n`,
  );
  console.log(`Wrote ${list.length} languages (A=${counts.A}, B=${counts.B}, C=${counts.C}).`);
}

main();
