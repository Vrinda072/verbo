/**
 * Evidence packet for one recovery case: everything Verbo knows, in one canonical JSON document whose
 * SHA-256 is printed on the PDF. Anyone holding the JSON can recompute the hash and check it matches.
 * Emails are masked; PayPal ids are included because they are what PayPal support needs.
 */
import { createHash } from "node:crypto";
import { asc, eq } from "drizzle-orm";
import { getDb, schema } from "@/db";
import { maskEmail } from "@/lib/log";
import { labelsFor } from "@/lib/bridge/readback";
import { evidenceScore, type EvidenceFacts } from "./meter";

export const PACKET_VERSION = "verbo-evidence/1";

/** JSON with object keys sorted recursively, no whitespace — stable bytes for hashing. */
export function canonicalJson(value: unknown): string {
  const norm = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(norm);
    if (v && typeof v === "object" && !(v instanceof Date)) {
      return Object.fromEntries(
        Object.keys(v as object)
          .sort()
          .filter((k) => (v as Record<string, unknown>)[k] !== undefined)
          .map((k) => [k, norm((v as Record<string, unknown>)[k])]),
      );
    }
    return v instanceof Date ? v.toISOString() : v;
  };
  return JSON.stringify(norm(value));
}

export const sha256 = (s: string) => createHash("sha256").update(s, "utf8").digest("hex");

export async function buildPacket(caseId: string, generatedAt = new Date()) {
  const db = await getDb();
  const [c] = await db.select().from(schema.cases).where(eq(schema.cases.id, caseId));
  if (!c) return null;
  const [t] = await db.select().from(schema.transfers).where(eq(schema.transfers.id, c.transferId));
  const [draft] = t?.draftId ? await db.select().from(schema.drafts).where(eq(schema.drafts.id, t.draftId)) : [];
  const [ret] = c.returnTransferId ? await db.select().from(schema.transfers).where(eq(schema.transfers.id, c.returnTransferId)) : [];
  const events = await db.select().from(schema.caseEvents).where(eq(schema.caseEvents.caseId, caseId)).orderBy(asc(schema.caseEvents.id));
  const transferEvents = t
    ? await db.select().from(schema.transferEvents).where(eq(schema.transferEvents.transferId, t.id)).orderBy(asc(schema.transferEvents.id))
    : [];
  const messages = await db.select().from(schema.caseMessages).where(eq(schema.caseMessages.caseId, caseId)).orderBy(asc(schema.caseMessages.id));

  const readback = draft ? labelsFor(draft.language) : null;
  const facts: EvidenceFacts = {
    hasPaymentRecord: Boolean(t?.orderId && t?.captureId),
    hasRiskRecord: Boolean(t?.riskLevel),
    hasUtterance: Boolean(draft),
    recipientViewed: events.some((e) => e.event === "VIEWED"),
    hasConversation: messages.length > 0 || events.some((e) => e.event === "REPLIED"),
    hasOutcome: events.some((e) => ["RETURNED", "REFUSED", "ESCALATED"].includes(e.event)),
    hasReturnPayment: Boolean(ret?.captureId),
  };

  const packet = {
    format: PACKET_VERSION,
    generatedAt,
    simulated: c.simulated === 1,
    disclaimer:
      "Generated by Verbo in the PayPal sandbox. Verbo cannot reverse payments; this packet documents what happened " +
      "so a recipient, PayPal support or a mediator can act on it.",
    case: {
      id: c.id,
      state: c.state,
      reason: c.reason,
      openedAt: c.createdAt,
      amount: { cents: c.amountCents, currency: c.currency },
      sender: { name: c.senderName, language: c.senderLanguage },
      recipient: { name: c.recipientName, language: c.recipientLanguage },
      remindersSent: c.remindersSent,
    },
    payment: t
      ? {
          transferId: t.id,
          state: t.state,
          sentAt: t.createdAt,
          senderEmail: maskEmail(t.senderEmail),
          recipientEmail: maskEmail(t.recipientEmail),
          paypal: { orderId: t.orderId, authorizationId: t.authorizationId, captureId: t.captureId, payoutBatchId: t.payoutBatchId },
          risk: t.risk ?? (t.riskLevel ? { level: t.riskLevel } : null),
          timeline: transferEvents.map((e) => ({ at: e.at, event: e.event, from: e.fromState, to: e.toState })),
        }
      : null,
    instruction: draft
      ? {
          transcript: draft.transcript,
          language: draft.language,
          understoodBy: draft.extractor,
          readBack: { templateLanguage: readback!.usedLang, machineTranslated: readback!.machineTranslated, reviewed: readback!.reviewed },
          confirmedAt: t?.createdAt,
        }
      : null,
    caseTimeline: events.map((e) => ({ at: e.at, event: e.event, actor: e.actor, from: e.fromState, to: e.toState })),
    conversation: messages.map((m) => ({
      at: m.at,
      author: m.author,
      text: m.text,
      lang: m.lang,
      translation: m.translatedText ? { text: m.translatedText, lang: m.translatedLang, by: m.translator } : null,
    })),
    returnPayment: ret
      ? { transferId: ret.id, state: ret.state, paypal: { orderId: ret.orderId, captureId: ret.captureId, payoutBatchId: ret.payoutBatchId } }
      : null,
    evidence: { score: evidenceScore(facts), facts },
  };

  const json = canonicalJson(packet);
  return { packet, json, sha256: sha256(json) };
}

export type EvidencePacket = NonNullable<Awaited<ReturnType<typeof buildPacket>>>;
